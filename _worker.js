function absolute(data, path, origin) {
  if (/^https?:\/\//i.test(path)) return path;
  return `${origin}/${String(path || "").replace(/^\/+/, "")}`;
}

function btoaUrl(value) {
  return btoa(value).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/g, "");
}

function atobUrl(value) {
  return atob(value.replace(/-/g, "+").replace(/_/g, "/"));
}

function fromBase64Url(value) {
  const binary = atobUrl(value);
  return Uint8Array.from(binary, c => c.charCodeAt(0));
}

function html(body, status = 200, headers = {}) {
  return new Response(body, { status, headers: { "Content-Type": "text/html; charset=UTF-8", ...headers } });
}

function json(body, status = 200) {
  return new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json; charset=UTF-8" } });
}

function text(body, contentType) {
  return new Response(body, { headers: { "Content-Type": `${contentType}; charset=UTF-8` } });
}

function xml(body) {
  return new Response(body, { headers: { "Content-Type": "application/xml; charset=UTF-8" } });
}

function redirect(location, headers = {}) {
  return new Response(null, { status: 303, headers: { Location: location, ...headers } });
}

function logout() {
  return redirect("/admin", { "Set-Cookie": "hyline_admin=; HttpOnly; Secure; SameSite=Lax; Path=/; Max-Age=0" });
}
