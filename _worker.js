async function currentUser(request, env) {
  const cookie = request.headers.get("Cookie") || "";
  const token = cookie.match(/(?:^|;)\s*hyline_admin=([^;]+)/)?.[1];
  if (!token) return null;
  try {
    const [payload, signature] = token.split(".");
    const expected = await hmac(payload, env.ADMIN_SESSION_SECRET || "troque-este-segredo");
    if (signature !== expected) return null;
    const data = JSON.parse(atobUrl(payload));
    if (!data.exp || data.exp < Date.now()) return null;
    return data;
  } catch {
    return null;
  }
}

async function signSession(payload, env) {
  const encoded = btoaUrl(JSON.stringify(payload));
  return `${encoded}.${await hmac(encoded, env.ADMIN_SESSION_SECRET || "troque-este-segredo")}`;
}

async function hmac(value, secret) {
  const key = await crypto.subtle.importKey("raw", new TextEncoder().encode(secret), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const signature = await crypto.subtle.sign("HMAC", key, new TextEncoder().encode(value));
  return btoaUrl(String.fromCharCode(...new Uint8Array(signature)));
}

async function verifyPassword(password, stored) {
  const [algo, iterations, salt, hash] = String(stored || "").split("$");
  if (algo !== "pbkdf2_sha256") return false;
  const key = await crypto.subtle.importKey("raw", new TextEncoder().encode(password), "PBKDF2", false, ["deriveBits"]);
  const bits = await crypto.subtle.deriveBits({ name: "PBKDF2", salt: fromBase64Url(salt), iterations: Number(iterations), hash: "SHA-256" }, key, 256);
  return btoaUrl(String.fromCharCode(...new Uint8Array(bits))) === hash;
}

